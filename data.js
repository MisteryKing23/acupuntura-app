// Mirror points to right side (body is symmetric, coordinates are for left side)
// Points on the midline (x ≈ 200 for front/back) don't get mirrored
const BODY_WIDTH = 400;
const CENTER_X = 200;
const TOLERANCE = 15;

function getMirroredPoints() {
  const all = [];
  ACUPOINTS.forEach(p => {
    all.push(p);
    const views = p.views;
    const needsMirror = Object.values(views).some(([x]) => Math.abs(x - CENTER_X) > TOLERANCE);
    if (needsMirror) {
      const mirrored = { ...p, _mirrored: true, views: {} };
      for (const [view, [x, y]] of Object.entries(views)) {
        mirrored.views[view] = [BODY_WIDTH - x, y];
      }
      all.push(mirrored);
    }
  });
  return all;
}
